// Generate the WebUI business index from the delivered client tree and the
// approved published-command/substrate contract in PLAN §5.6.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const root = fileURLToPath(new URL("../", import.meta.url));
const sourceRoot = path.join(root, "packages/webui/src/client");
const guidePath = path.join(root, "packages/webui/AGENTS.md");
const begin = "<!-- BEGIN GENERATED WEBUI BUSINESS NAVIGATION -->";
const end = "<!-- END GENERATED WEBUI BUSINESS NAVIGATION -->";

// Published command labels and substrate reads are the accepted §5.6 contract.
// Paths are discovered below so the index follows the delivered tree.
const businesses = [
  ["sessions", "create / select / archive / fork / rename / import / export / delete; mark-read; contextWindowUsage(sessionId); purge", "read-model, in-flight-read, intents"],
  ["composer", "setDraft; recordComposerInput; attachments; chooseMention; chooseCommand; queue commands", "read-model, in-flight-read, intents"],
  ["transcript", "load a history page; load older; request a turn review", "read-model, in-flight-read"],
  ["workspace", "dispatchWorkspacePanel; file read; git mutate", "read-model, in-flight-read"],
  ["interactions", "replacePendingPermissions; removePendingPermission; applyQuestionnaire", "in-flight-read"],
  ["goal", "createGoal; patchGoal; clearGoal; refreshGoal; goal-mode entry/exit", "in-flight-read"],
  ["models", "listModels; selectModel; provider CRUD", "none"],
  ["plugins", "plugin management operations", "none"],
  ["settings", "setGlobalInstructions; setAgentMemory; setUserProfile; setMemorySettings", "read-model"],
  ["account", "signOut; beginAccountLogin; cancelAccountLogin; claimSignin; forceRefresh", "read-model"],
  ["shell", "no commands of its own; invokes each business's published commands", "none"],
  ["turn", "stream-phase group; turn-lifecycle group; turn capability slice", "self"],
];

const layers = [
  ["Presentation", "components"],
  ["Application owner", "application"],
  ["Projection", "projection"],
  ["Browser contracts", "contracts"],
];

function existingBusinessPaths(business, layer) {
  const relative = `client/${layer}/${business}/`;
  return existsSync(path.join(sourceRoot, layer, business)) ? `\`${relative}\`` : "—";
}

function render() {
  const rows = businesses.map(([business, published, substrate]) => {
    const paths = layers.map(([, layer]) => existingBusinessPaths(business, layer));
    if (business === "sessions" && existsSync(path.join(sourceRoot, "application/session-store.ts"))) {
      paths[1] += ", `client/application/session-store.ts`";
    }
    if (business === "shell" && existsSync(path.join(sourceRoot, "main.tsx"))) {
      paths[1] += ", `client/main.tsx`";
    }
    if (business !== "turn" && paths.slice(0, 4).every((entry) => entry === "—")) {
      throw new Error(`business navigation: ${business} has no delivered business directory`);
    }
    return `| \`${business}\` | ${paths.join(" | ")} | ${published} | ${substrate} |`;
  });
  return [
    "<!-- Generated by scripts/webui-business-navigation.mjs. Do not edit by hand. -->",
    "| Business | Presentation | Application owner | Projection | Browser contracts | Published contract (§5.6) | Substrate consumption |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
  ].join("\n");
}

function updateGuide(contents, generated) {
  const start = contents.indexOf(begin);
  const finish = contents.indexOf(end);
  if (start < 0 || finish < start) {
    throw new Error(`business navigation: ${guidePath} must contain its generated block markers`);
  }
  return `${contents.slice(0, start + begin.length)}\n${generated}\n${contents.slice(finish)}`;
}

const { values } = parseArgs({ options: { write: { type: "boolean", default: false } } });
const current = readFileSync(guidePath, "utf8");
const updated = updateGuide(current, render());
if (values.write) {
  writeFileSync(guidePath, updated);
  console.log("webui-business-navigation: updated packages/webui/AGENTS.md");
} else if (updated !== current) {
  console.error("webui-business-navigation: navigation table is stale; run `pnpm gen:webui-business-navigation` and commit the result");
  process.exit(1);
} else {
  console.log("webui-business-navigation: navigation table matches the delivered tree and §5.6 contract");
}
