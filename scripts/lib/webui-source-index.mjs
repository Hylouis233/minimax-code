import { readdirSync } from "node:fs";
import path from "node:path";
import ts from "typescript";

export function sourceFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const file = path.join(directory, entry.name);
    return entry.isDirectory() ? sourceFiles(file) : /\.(?:ts|tsx)$/u.test(entry.name) ? [file] : [];
  }).sort();
}

// 空目录不属于可交付源码；同一职责的多个实际位置全部保留。
export function discoverModules(clientRoot) {
  const modules = new Map();
  for (const absolute of sourceFiles(clientRoot)) {
    const relative = path.relative(clientRoot, absolute).split(path.sep).join("/");
    const parts = relative.split("/");
    let name, role, location;
    if (parts[0] === "features" && parts.length >= 4) {
      [, name, role] = parts;
      location = `client/features/${name}/${role}/`;
    } else if (["components", "application", "projection", "contracts", "bindings"].includes(parts[0]) && parts.length >= 3) {
      name = parts[1];
      role = parts[0] === "components" ? "ui" : parts[0];
      location = `client/${parts[0]}/${name}/`;
    } else continue;
    if (!modules.has(name)) modules.set(name, new Map());
    const roles = modules.get(name);
    if (!roles.has(role)) roles.set(role, new Set());
    roles.get(role).add(location);
  }
  return new Map([...modules].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0));
}

export function renderNavigation(clientRoot) {
  const roles = ["ui", "application", "projection", "bindings", "contracts"];
  return [
    "<!-- Generated by scripts/webui-business-navigation.mjs. Do not edit by hand. -->",
    "| Module | Presentation | Application | Projection | Bindings | Contracts |",
    "| --- | --- | --- | --- | --- | --- |",
    ...[...discoverModules(clientRoot)].map(([name, locations]) =>
      `| \`${name}\` | ${roles.map((role) => [...(locations.get(role) ?? [])].sort().map((p) => `\`${p}\``).join(", ") || "—").join(" | ")} |`),
  ].join("\n");
}

// 记录实际导出和继承成员，不把模块导出推断为业务公共命令。
export function renderCommandSurface(clientRoot, compilerOptions) {
  const files = sourceFiles(clientRoot);
  const program = ts.createProgram(files, { ...compilerOptions, noEmit: true });
  const checker = program.getTypeChecker();
  const printer = ts.createPrinter({ removeComments: true });
  const rows = [];
  const escape = (value) => value.replace(/import\("([^"]+)"\)/gu, (match, target) => path.isAbsolute(target)
    ? `import("${path.posix.normalize(`client/${path.relative(clientRoot, target).split(path.sep).join("/")}`)}")` : match)
    .replace(/\s+/gu, " ").replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll("|", "&#124;").replaceAll("`", "&#96;");
  for (const file of files) {
    const relative = path.relative(clientRoot, file).split(path.sep).join("/");
    if (!/(?:^|\/)(?:contracts|application)\//u.test(relative)) continue;
    const source = program.getSourceFile(file);
    const module = checker.getSymbolAtLocation(source);
    if (!module) continue;
    for (const symbol of checker.getExportsOfModule(module)) {
      const resolved = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
      const declaration = resolved.declarations?.find((d) => d.getSourceFile() === source) ?? resolved.declarations?.[0];
      if (!declaration || !(ts.isInterfaceDeclaration(declaration) || ts.isTypeAliasDeclaration(declaration) || ts.isFunctionDeclaration(declaration) || ts.isVariableDeclaration(declaration))) continue;
      const owner = relative.startsWith("features/") ? relative.split("/")[1] : relative.split("/").length > 2 ? relative.split("/")[1] : "application-shared";
      if (ts.isFunctionDeclaration(declaration) || ts.isVariableDeclaration(declaration)) {
        const type = checker.getTypeOfSymbolAtLocation(resolved, declaration);
        const signatures = type.getCallSignatures();
        if (ts.isFunctionDeclaration(declaration) && !signatures.length) throw new Error(`Cannot resolve signature: ${relative}:${symbol.name}`);
        if (signatures.length) {
          for (const signature of signatures) rows.push([owner, relative, symbol.name, checker.signatureToString(signature, declaration, ts.TypeFormatFlags.NoTruncation)]);
        } else if (type.getProperties().some((member) => checker.getTypeOfSymbolAtLocation(member, declaration).getCallSignatures().length)) {
          rows.push([owner, relative, symbol.name, checker.typeToString(type, declaration, ts.TypeFormatFlags.NoTruncation)]);
        }
      } else {
        const type = checker.getDeclaredTypeOfSymbol(resolved);
        rows.push([owner, relative, symbol.name, printer.printNode(ts.EmitHint.Unspecified, declaration, declaration.getSourceFile())]);
        for (const member of type.flags & (ts.TypeFlags.Object | ts.TypeFlags.Intersection) ? checker.getPropertiesOfType(type) : []) {
          // 本地成员已完整保留在声明行，只展开来自继承/映射类型的成员。
          if (member.declarations?.some((d) => d.getSourceFile() === declaration.getSourceFile() && d.pos >= declaration.pos && d.end <= declaration.end)) continue;
          rows.push([owner, relative, `${symbol.name}.${member.name}`, `${member.flags & ts.SymbolFlags.Optional ? "optional " : ""}${checker.typeToString(checker.getTypeOfSymbolAtLocation(member, declaration), declaration, ts.TypeFormatFlags.NoTruncation)}`]);
        }
      }
    }
  }
  rows.sort((a, b) => a.join("\0") < b.join("\0") ? -1 : a.join("\0") > b.join("\0") ? 1 : 0);
  return [
    "<!-- Generated by scripts/webui-command-surface.mjs. Do not edit by hand. -->", "", "# WebUI exported application and contract surface", "",
    "Discovered from exported interfaces, type aliases, functions and callable values in application/ and contracts/ modules, including re-exports.",
    "Module exports include reads and internal owner contracts; this index does not declare every export a public business command.",
    "Declarations, inherited members and resolved signatures are checked. New modules require no registration list.",
    "Regenerate with `pnpm gen:webui-commands`.", "",
    "| Module | Source | Export / member | Declaration / signature |", "| --- | --- | --- | --- |",
    ...rows.map((row) => `| ${row.map(escape).join(" | ")} |`), "",
  ].join("\n");
}
